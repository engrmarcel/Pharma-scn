<?php

namespace App\Console\Commands;

use Illuminate\Console\Attributes\Description;
use Illuminate\Console\Attributes\Signature;
use Illuminate\Console\Command;
use Illuminate\Support\Facades\DB;
use Symfony\Component\Process\Process;

/**
 * Regenerates database/sql/pharmaceutical_supply_chain_schema.sql from the
 * migrated database, so the SQL file never describes tables that do not
 * exist. SchemaSnapshotTest fails if the file drifts from the migrations.
 */
#[Signature('schema:export-sql {--connection= : Database connection to dump (default: the default connection)}')]
#[Description('Write the migrated schema (structure only) to database/sql/pharmaceutical_supply_chain_schema.sql')]
class ExportSchemaSql extends Command
{
    public const PATH = 'database/sql/pharmaceutical_supply_chain_schema.sql';

    public function handle(): int
    {
        $connection = $this->option('connection') ?: config('database.default');
        $config = config("database.connections.$connection");

        $process = new Process(array_filter([
            env('MYSQLDUMP_PATH', 'mysqldump'),
            '--no-data', '--skip-comments', '--skip-add-drop-table', '--routines=false', '--triggers=false',
            '--host='.$config['host'], '--port='.$config['port'], '--user='.$config['username'],
            $config['password'] !== '' && $config['password'] !== null ? '--password='.$config['password'] : null,
            $config['database'],
        ]));
        $process->setTimeout(120)->run();

        if (! $process->isSuccessful()) {
            $this->error('mysqldump failed: '.trim($process->getErrorOutput()));
            $this->line('Set MYSQLDUMP_PATH if mysqldump is not on PATH (XAMPP: C:\\xampp\\mysql\\bin\\mysqldump.exe).');

            return self::FAILURE;
        }

        // Strip server-specific noise so the file diffs cleanly between machines.
        $sql = preg_replace(['/^\/\*!\d+ SET .*?\*\/;\s*$/m', '/ AUTO_INCREMENT=\d+/'], '', $process->getOutput());
        $migration = DB::connection($connection)->table('migrations')->orderByDesc('id')->value('migration');

        $header = "-- Pharmaceutical Supply Chain Network: database structure\n"
            ."-- GENERATED by `php artisan schema:export-sql` from the migrated database. Do not edit by hand;\n"
            ."-- migrations are the source of truth. Latest migration: {$migration}\n"
            ."-- Reference data (countries, permissions, roles, units...) is loaded by `php artisan db:seed`.\n\n"
            ."SET NAMES utf8mb4;\nSET FOREIGN_KEY_CHECKS = 0;\n\n";

        @mkdir(base_path('database/sql'), 0755, true);
        file_put_contents(base_path(self::PATH), $header.trim(preg_replace("/\n{3,}/", "\n\n", $sql))."\n\nSET FOREIGN_KEY_CHECKS = 1;\n");

        $this->info('Wrote '.self::PATH);

        return self::SUCCESS;
    }
}
